-- Caucasus Transfer: driver price offers
-- Run this script in Supabase SQL Editor after confirming the current drivers/orders schema.

create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  driver_id bigint not null references public.drivers(id) on delete cascade,
  price numeric(10,2) not null check (price > 0),
  message text,
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'rejected', 'withdrawn')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint offers_order_driver_unique unique (order_id, driver_id)
);

create index if not exists offers_order_id_idx on public.offers(order_id);
create index if not exists offers_driver_id_idx on public.offers(driver_id);
create index if not exists offers_status_idx on public.offers(status);

alter table public.offers enable row level security;

grant select, insert on public.offers to authenticated;
grant usage, select on sequence public.offers_id_seq to authenticated;

drop policy if exists "Approved drivers can submit own offers" on public.offers;
create policy "Approved drivers can submit own offers"
on public.offers
for insert
to authenticated
with check (
  exists (
    select 1
    from public.drivers d
    where d.id = driver_id
      and d.user_id = auth.uid()
      and d.approved = true
      and d.status = 'approved'
  )
  and exists (
    select 1
    from public.orders o
    where o.id = order_id
      and o.status = 'open'
      and o.assigned_driver_id is null
  )
);

drop policy if exists "Drivers can view own offers" on public.offers;
create policy "Drivers can view own offers"
on public.offers
for select
to authenticated
using (
  exists (
    select 1
    from public.drivers d
    where d.id = driver_id
      and d.user_id = auth.uid()
  )
);

